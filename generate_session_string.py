#!/usr/bin/env python3
"""
NekoUB Session String Generator
Generate a session string for your userbot.

The generated session string is written directly into the `.env` file in this
repo, so there is nothing to copy-paste afterwards.

Run it with the project virtualenv:
    .venv/bin/python generate_session_string.py
"""

import asyncio
import os
from pathlib import Path

from dotenv import dotenv_values
from pyrogram import Client

ENV_PATH = Path(__file__).resolve().parent / ".env"


def check_env_permissions():
    """Ensure .env is writable before starting login flow."""
    if not ENV_PATH.exists():
        return
    if not os.access(ENV_PATH, os.W_OK):
        print(f"\n❌ Error: Permission denied: {ENV_PATH}")
        print("   The .env file is not writable by current user.")
        print(f"   Run: chown $USER:$USER {ENV_PATH} && chmod 600 {ENV_PATH}")
        raise SystemExit(1)


def print_banner():
    """Print cute banner."""
    print("\n" + "=" * 50)
    print("   🐱 NekoUB Session String Generator")
    print("   Nya~ Let's get your session string!")
    print("=" * 50 + "\n")


def load_env_defaults():
    """Read API_ID / API_HASH from an existing .env, if present."""
    if not ENV_PATH.exists():
        return "", ""
    values = dotenv_values(ENV_PATH)
    api_id = (values.get("API_ID") or "").strip()
    api_hash = (values.get("API_HASH") or "").strip()
    # Treat the placeholder value from .env.example as "not set"
    if api_hash == "your_api_hash_here":
        api_hash = ""
    return api_id, api_hash


def save_session_string(session_string: str):
    """Write/replace SESSION_STRING in .env, keeping every other line."""
    lines = []
    if ENV_PATH.exists():
        lines = ENV_PATH.read_text().splitlines()

    replaced = False
    for i, line in enumerate(lines):
        if line.strip().startswith("SESSION_STRING="):
            lines[i] = f"SESSION_STRING={session_string}"
            replaced = True
            break

    if not replaced:
        # Add a small spacer so the value is easy to find
        if lines and lines[-1].strip() != "":
            lines.append("")
        lines.append("# Session String (auto-generated by generate_session_string.py)")
        lines.append(f"SESSION_STRING={session_string}")

    ENV_PATH.write_text("\n".join(lines).rstrip("\n") + "\n")


async def generate_session():
    """Generate session string."""
    check_env_permissions()
    print_banner()

    default_api_id, default_api_hash = load_env_defaults()

    # Get API credentials (defaults come from .env when available)
    print("📝 Please enter your Telegram API credentials")
    print("Get them from: https://my.telegram.org/apps")
    print("(Press Enter to use the value already in .env)\n")

    try:
        raw_id = input(f"Enter your API_ID [{default_api_id}]: ").strip()
        api_id_str = raw_id or default_api_id
        api_id = int(api_id_str)

        raw_hash = input(f"Enter your API_HASH [{default_api_hash}]: ").strip()
        api_hash = raw_hash or default_api_hash
        if not api_hash:
            print("\n❌ Error: API_HASH is required!")
            return

        print("\n🔄 Generating session string...")
        print("   Telegram will ask for your phone number, the login code,")
        print("   and your 2FA password (if enabled).\n")

        # Create temporary client - this triggers the interactive login flow
        try:
            async with Client(
                "temp_session", api_id=api_id, api_hash=api_hash, in_memory=True
            ) as app:
                # Get session string
                session_string = await app.export_session_string()
        except Exception as e:
            if "bot token" in str(e).lower():
                print("\n❌ Error: This script is for user sessions only (phone number login).")
                print("   Do not use a bot token. Set BOT_TOKEN separately in .env.")
                print("   To get a user session string, use a phone number.")
                return
            raise

        # Persist it into .env automatically
        save_session_string(session_string)

        print("\n" + "=" * 50)
        print("✅ Session string generated and saved to .env!")
        print("=" * 50 + "\n")

        print(f"📁 Written to: {ENV_PATH}")
        print(f"🔑 Length: {len(session_string)} chars\n")

        print("📋 Your SESSION_STRING (for reference):\n")
        print(session_string)
        print("\n" + "=" * 50)

        print("\n📝 Next steps:")
        print("1. Start the bot:  systemctl --user start nekoub")
        print("   (or run manually:  .venv/bin/python main.py)")
        print("\n🐱 Nya~ You're all set!\n")

    except ValueError:
        print("\n❌ Error: API_ID must be a number!")
    except KeyboardInterrupt:
        print("\n\n⚠️  Cancelled.")
    except Exception as e:
        print(f"\n❌ Error: {type(e).__name__}: {e}")
        print("\nMake sure you entered correct API credentials and login code!")


if __name__ == "__main__":
    asyncio.run(generate_session())
